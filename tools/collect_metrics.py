"""Collect every number this repository publishes into docs/metrics.json.

The README, the badges and the docs read their numbers from this file rather
than carrying their own copies. tools/check_numbers.py then fails CI when a
published figure no longer matches a measured one.

Usage:
    python tools/collect_metrics.py
"""

from __future__ import annotations

import json
import subprocess
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from ibr.account.generate import generate  # noqa: E402
from ibr.config import Config  # noqa: E402
from ibr.graph.build import build_graph  # noqa: E402
from ibr.graph.edges import DEFINITIONS  # noqa: E402
from ibr.graph.reach import analyse  # noqa: E402
from ibr.logging import configure  # noqa: E402

BENCHMARK = ROOT / "benchmark" / "results" / "benchmark.json"
COVERAGE_XML = ROOT / "coverage.xml"
OUT = ROOT / "docs" / "metrics.json"
HEADLINE_PRINCIPALS = 2_000
HEADLINE_SEED = 7


def _coverage_pct() -> float | None:
    if not COVERAGE_XML.exists():
        return None
    rate = ET.parse(COVERAGE_XML).getroot().get("line-rate")
    return round(float(rate) * 100, 1) if rate else None


def _test_count() -> int | None:
    result = subprocess.run(
        [sys.executable, "-m", "pytest", "--collect-only", "-q"],
        cwd=ROOT, capture_output=True, text=True,
    )
    total = 0
    for line in result.stdout.splitlines():
        head, _, tail = line.rpartition(":")
        if head.endswith(".py") and tail.strip().isdigit():
            total += int(tail.strip())
    return total or None


def _commit_count() -> int | None:
    result = subprocess.run(["git", "rev-list", "--count", "HEAD"], cwd=ROOT, capture_output=True, text=True)
    return int(result.stdout.strip()) if result.returncode == 0 else None


def _headline() -> dict:
    configure("WARNING")
    config = Config()
    account_path = ROOT / "data" / "generated" / f"metrics_{HEADLINE_PRINCIPALS}.json"
    result = generate(account_path, HEADLINE_PRINCIPALS, seed=HEADLINE_SEED)
    graph = build_graph(result.account, config)
    report = analyse(graph, result.account.account_id, config)

    return {
        "account_kind": "synthetic",
        "account_seed": HEADLINE_SEED,
        "principals": report.principal_count,
        "edges": graph.number_of_edges(),
        "max_hops": config.max_hops,
        "escalation_edge_kinds": len(DEFINITIONS),
        "already_admin": len(report.admin_principals),
        "escalating": len(report.escalating),
        "escalating_pct": round(report.escalating_pct, 1),
        "labelled_least_privilege": len(report.labelled_least_privilege),
        "mislabelled": len(report.mislabelled),
        "mislabelled_pct": round(report.mislabelled_pct, 1),
        "at_one_hop": len(report.at_hop(1)),
        "at_two_hops": len(report.at_hop(2)),
        "at_three_hops": len(report.at_hop(3)),
        "conditional_only": sum(1 for f in report.escalating if f.conditional_only),
        "self_scoped_principals": result.shapes.get("self_scoped", 0),
    }


def main() -> int:
    payload: dict = {
        "note": (
            "Generated by tools/collect_metrics.py. Numbers derived from the bundled synthetic "
            "account are simulations and are labelled as such wherever they are published."
        ),
        "analysis": _headline(),
        "quality": {
            "test_coverage_pct": _coverage_pct(),
            "test_count": _test_count(),
            "commit_count": _commit_count(),
        },
    }

    if BENCHMARK.exists():
        benchmark = json.loads(BENCHMARK.read_text(encoding="utf-8"))
        payload["performance"] = {
            "hardware": benchmark["hardware"],
            "repeats": benchmark["repeats"],
            "scenarios": [
                {
                    "principals": s["principals"],
                    "account_mb": round(s["account_bytes"] / 1e6, 1),
                    "edges": s["edges"],
                    "build_median_s": s["build"]["median_s"],
                    "analyse_median_s": s["analyse"]["median_s"],
                    "mislabelled_pct": s["mislabelled_pct"],
                }
                for s in benchmark["scenarios"]
            ],
        }

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")
    print(f"wrote {OUT}")
    print(json.dumps(payload["analysis"], indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
