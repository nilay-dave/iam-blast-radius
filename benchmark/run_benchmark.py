"""Measure graph build and reachability runtime across account sizes.

Writes raw results to benchmark/results/. Every number the README publishes
about performance comes from a run of this file.

Usage:
    python benchmark/run_benchmark.py [--sizes 200 2000 20000]
"""

from __future__ import annotations

import argparse
import json
import platform
import statistics
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from ibr.account.generate import generate  # noqa: E402
from ibr.config import Config  # noqa: E402
from ibr.graph.build import build_graph  # noqa: E402
from ibr.graph.reach import analyse  # noqa: E402
from ibr.logging import configure  # noqa: E402

RESULTS = Path(__file__).parent / "results"
DEFAULT_SIZES = (200, 2_000, 20_000)
REPEATS = 3


def _hardware() -> dict:
    import os

    return {
        "platform": platform.platform(),
        "python": platform.python_version(),
        "processor": platform.machine(),
        "cpu_count": os.cpu_count(),
    }


def _time(fn, repeats: int):
    samples, value = [], None
    for _ in range(repeats):
        start = time.perf_counter()
        value = fn()
        samples.append(time.perf_counter() - start)
    samples.sort()
    return value, {
        "repeats": repeats,
        "min_s": round(samples[0], 4),
        "median_s": round(statistics.median(samples), 4),
        "max_s": round(samples[-1], 4),
    }


def run(sizes, repeats, workdir: Path) -> dict:
    configure("WARNING")
    config = Config()
    workdir.mkdir(parents=True, exist_ok=True)
    scenarios = []

    for size in sizes:
        account_path = workdir / f"bench_{size}.json"
        result, generation = _time(lambda p=account_path, n=size: generate(p, n, seed=7), 1)
        account = result.account

        graph, build_timing = _time(lambda a=account: build_graph(a, config), repeats)
        account_id = account.account_id
        report, analyse_timing = _time(lambda g=graph, aid=account_id: analyse(g, aid, config), repeats)

        scenarios.append({
            "requested_principals": size,
            "principals": result.principals,
            "account_bytes": account_path.stat().st_size,
            "edges": graph.number_of_edges(),
            "generate": generation,
            "build": build_timing,
            "analyse": analyse_timing,
            "principals_per_second_build": round(result.principals / build_timing["median_s"]),
            "already_admin": len(report.admin_principals),
            "escalating": len(report.escalating),
            "escalating_pct": round(report.escalating_pct, 2),
            "labelled_least_privilege": len(report.labelled_least_privilege),
            "mislabelled": len(report.mislabelled),
            "mislabelled_pct": round(report.mislabelled_pct, 2),
            "by_hop": {str(hop): len(report.at_hop(hop)) for hop in range(1, config.max_hops + 1)},
        })
        account_path.unlink(missing_ok=True)
        print(
            f"  {result.principals:>7,} principals  build {build_timing['median_s']:>8.3f}s  "
            f"analyse {analyse_timing['median_s']:>7.3f}s  edges {graph.number_of_edges():>10,}  "
            f"mislabelled {report.mislabelled_pct:5.1f}%"
        )

    return {
        "hardware": _hardware(),
        "repeats": repeats,
        "max_hops": config.max_hops,
        "account": "synthetic, generated by ibr generate at seed 7",
        "scenarios": scenarios,
    }


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--sizes", type=int, nargs="+", default=list(DEFAULT_SIZES))
    parser.add_argument("--repeats", type=int, default=REPEATS)
    parser.add_argument("--workdir", type=Path, default=Path("data/generated/bench"))
    args = parser.parse_args()

    print(f"benchmarking {len(args.sizes)} account sizes, {args.repeats} repeats each")
    payload = run(tuple(args.sizes), args.repeats, args.workdir)

    RESULTS.mkdir(parents=True, exist_ok=True)
    out = RESULTS / "benchmark.json"
    out.write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")
    print(f"\nwrote {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
